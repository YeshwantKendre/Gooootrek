// Generates supabase/seed.sql from src/data/treks.json.
// Usage: npm run seed:sql
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const treks = JSON.parse(readFileSync(resolve(root, "src/data/treks.json"), "utf8"));

const COLUMNS = [
  "slug", "name", "state", "region", "mountain_range", "difficulty", "duration_days",
  "max_altitude_m", "distance_km", "best_months", "seasons", "base_camp", "nearest_airport",
  "nearest_railway", "summary", "description", "highlights", "tags", "permits",
  "cover_image_url", "is_featured",
];

const str = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const num = (v) => (v == null ? "null" : String(Number(v)));
const arr = (v) =>
  !v || v.length === 0 ? "'{}'::text[]" : `array[${v.map(str).join(", ")}]::text[]`;

function value(col, t) {
  const v = t[col];
  switch (col) {
    case "difficulty": return `${str(v)}::public.trek_difficulty`;
    case "duration_days": case "max_altitude_m": case "distance_km": return num(v);
    case "best_months": case "seasons": case "highlights": case "tags": return arr(v);
    case "is_featured": return v ? "true" : "false";
    default: return str(v);
  }
}

const updates = COLUMNS.filter((c) => c !== "slug").map((c) => `${c} = excluded.${c}`).join(",\n  ");
const rows = treks.map((t) => `  (${COLUMNS.map((c) => value(c, t)).join(", ")})`).join(",\n");

const sql = `-- Generated by scripts/generate-seed.mjs from src/data/treks.json. Do not edit by hand.
-- ${treks.length} treks. Run with: psql / Supabase SQL editor.

insert into public.treks (${COLUMNS.join(", ")})
values
${rows}
on conflict (slug) do update set
  ${updates};
`;

const out = resolve(root, "supabase/seed.sql");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(`Wrote ${treks.length} treks to supabase/seed.sql`);
